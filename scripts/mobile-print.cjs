const { chromium, devices } = require('playwright-core')
const path = require('path')
;(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
  const ctx = await browser.newContext({ ...devices['iPhone 13'] })
  const page = await ctx.newPage()
  await page.goto('http://127.0.0.1:8080/', { waitUntil: 'networkidle' })
  await page.waitForTimeout(2500)
  await page.locator('.book-card').first().locator('.book-cover').click()
  await page.waitForTimeout(1500)
  await page.locator('.mobile-tabs button', { hasText: 'Print' }).click()
  await page.waitForTimeout(5000)
  await page.locator('.preview-toolbar').scrollIntoViewIfNeeded()
  await page.waitForTimeout(600)
  await page.screenshot({ path: path.join(process.env.TMPDIR, 'shots', 'm5-preview.png') })
  await page.locator('.checks-col').scrollIntoViewIfNeeded()
  await page.waitForTimeout(600)
  await page.screenshot({ path: path.join(process.env.TMPDIR, 'shots', 'm6-checks.png') })
  await browser.close()
})()
