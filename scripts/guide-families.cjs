// Writes the audience + genre family tables into README.md from src/data/layouts2.ts,
// so the guide always matches what the app really does. Re-run after changing layouts2.ts.
const fs = require('fs');
const src = fs.readFileSync('src/data/layouts2.ts', 'utf8');
const rx = /family\('(\w+)', '([^']+)', '([^']+)',\s*\n\s*'((?:[^'\\]|\\.)*)',\s*\n\s*'([^']+)',[\s\S]*?\{ trim: '([^']+)', font: '([^']+)', size: ([\d.]+), leading: ([\d.]+)([^}]*)\}/g;
const rows = [];
let m;
while ((m = rx.exec(src))) {
    const [, id, name, , blurb, , trim, font, size, leading, rest] = m;
    const dims = trim.replace('x', ' × ');
    const bits = [];
    if (/dropCap: true/.test(rest)) bits.push('drop caps');
    if (/numbers: 'words'/.test(rest)) bits.push('chapter numbers in words');
    if (/numbers: 'none'/.test(rest)) bits.push('unnumbered chapters');
    if (/toc: true/.test(rest)) bits.push('contents page');
    if (/justify: false/.test(rest)) bits.push('ragged right');
    const orn = /ornament: '(\w+)'/.exec(rest);
    if (orn && orn[1] !== 'none') bits.push(orn[1] + ' scene breaks');
    rows.push({ id, name, dims, font, size, leading, bits, blurb: blurb.replace(/\\u2019/g, '’').replace(/\\'/g, "'") });
}
if (rows.length !== 18) { console.error('expected 18 families, parsed ' + rows.length); process.exit(1); }
const writers = ['firstnovel', 'series', 'professional', 'family', 'retirees', 'hobby', 'selfpub'];
const line = r => `| **${r.name}** | ${r.dims} | ${r.font} ${r.size} pt, leading ${r.leading}${r.bits.length ? '; ' + r.bits.join(', ') : ''} |`;
const table = list => '| Family | Page | Type and what makes it itself |\n|---|---|---|\n' + list.map(line).join('\n');
const block = `<!-- families:start (generated by scripts/guide-families.cjs) -->
Eighteen more families are built for particular writers and genres. Each has its own worked example, so you can open one and see the page it makes.

**For writers**

${table(rows.filter(r => writers.includes(r.id)))}

**For genres**

${table(rows.filter(r => !writers.includes(r.id)))}

Every family also sets its own front and back matter (for example Fantasy adds a character list, prologue and glossary; Self-publishers adds Also By, About the Author and a colophon), running heads, folios and a matching cover palette. Pick the closest one, then change any rule on **Print layout**.
<!-- families:end -->`;
let r = fs.readFileSync('README.md', 'utf8').replace(/\r\n/g, '\n');
const re = /<!-- families:start[\s\S]*?<!-- families:end -->/;
if (re.test(r)) r = r.replace(re, () => block);
else {
    const anchor = '**Seven examples are already in your library**';
    if (!r.includes(anchor)) { console.error('anchor missing'); process.exit(1); }
    r = r.replace(anchor, () => block + '\n\n' + anchor);
}
r = r.replace('**Seven examples are already in your library**, one per family.', '**25 examples are already in your library**, one per family.');
fs.writeFileSync('README.md', r);
console.log('wrote ' + rows.length + ' families into README.md');
