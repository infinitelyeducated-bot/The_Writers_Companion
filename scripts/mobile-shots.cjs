const { chromium, devices } = require('playwright-core')
const path = require('path')
;(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
  const out = path.join(process.env.TMPDIR, 'shots')
  const ctx = await browser.newContext({ ...devices['iPhone 13'] })
  const page = await ctx.newPage()
  await page.goto('http://127.0.0.1:8080/', { waitUntil: 'networkidle' })
  await page.waitForTimeout(2500)
  await page.screenshot({ path: path.join(out, 'm1-library.png') })
  await page.locator('.book-cover').first().click()
  await page.waitForTimeout(1800)
  await page.screenshot({ path: path.join(out, 'm2-write.png') })
  await page.locator('.tree-toggle').click()
  await page.waitForTimeout(500)
  await page.screenshot({ path: path.join(out, 'm3-tree.png') })
  await page.mouse.click(360, 500) // tap the scrim to the right of the drawer
  await page.waitForTimeout(400)
  await page.locator('.mobile-tabs button', { hasText: 'Print' }).click()
  await page.waitForTimeout(4500)
  await page.screenshot({ path: path.join(out, 'm4-print.png') })
  console.log('device width', page.viewportSize())
  await browser.close()
})()
