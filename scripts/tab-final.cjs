const { chromium } = require('playwright-core')
;(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
  const page = await (await browser.newContext({ viewport: { width: 1500, height: 950 } })).newPage()
  page.on('pageerror', (e) => console.log('PAGEERROR', e.message))
  page.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE', m.text()) })
  await page.goto('http://localhost:5180/', { waitUntil: 'networkidle' })
  await page.waitForTimeout(2000)
  await page.locator('.example-card', { hasText: 'Trade fiction' }).locator('button', { hasText: 'Open example' }).click()
  await page.waitForTimeout(2500)
  await page.locator('.manuscript p').first().click()
  await page.keyboard.press('Control+End')
  const codes = () => page.evaluate(() => { const ps=[...document.querySelectorAll('.manuscript p')]; return [...ps[ps.length-2].textContent].map(c=>c.charCodeAt(0)) })
  await page.keyboard.press('Enter')
  await page.keyboard.press('Tab')
  await page.keyboard.type('ONE TAB')
  console.log('1 tab ->', JSON.stringify(await codes()))
  await page.keyboard.press('Enter')
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  await page.keyboard.type('THREE TABS')
  console.log('3 tabs ->', JSON.stringify(await codes()))
  await page.keyboard.press('Home')
  await page.keyboard.press('Shift+Tab')
  console.log('shift-tab ->', JSON.stringify(await codes()))
  await page.waitForTimeout(1600)
  await page.getByRole('button', { name: 'Print layout' }).click()
  await page.waitForTimeout(4000)
  await page.locator('label:has-text("All pages") input').click()
  await page.waitForTimeout(1600)
  const printed = await page.evaluate(() => {
    const all = [...document.querySelectorAll('.book-page p')]
    const p = all.find((x) => x.textContent.includes('THREE'))
    return { found: !!p, count: all.length, hasNbsp: all.some((x) => x.textContent.includes('\u00a0')), sample: p ? [...p.textContent].slice(0, 12).map((c) => c.charCodeAt(0)) : all.slice(-2).map(x=>x.textContent.slice(0,30)) }
  })
  console.log('print layer ->', JSON.stringify(printed), '(32 = ordinary space, 160 = nbsp)')
  await browser.close()
})()
